"use client";

import { useEffect, useState } from "react";

type RunMeta = {
  image: string;
  kind?: string;
  source?: string;
  backend?: string;
  job_id?: string;
  timestamp?: string;
  caption?: string;
};

const byNewest = (a: RunMeta, b: RunMeta) =>
  (b.timestamp ?? "").localeCompare(a.timestamp ?? "");

export default function Runs() {
  const [runs, setRuns] = useState<RunMeta[] | null>(null);

  useEffect(() => {
    let alive = true;
    fetch("/hardware_runs/manifest.json")
      .then((r) => (r.ok ? r.json() : []))
      .then((data) => {
        if (alive) setRuns(Array.isArray(data) ? data : []);
      })
      .catch(() => {
        if (alive) setRuns([]);
      });
    return () => {
      alive = false;
    };
  }, []);

  const hardware = (runs ?? []).filter((m) => m.source === "hardware").sort(byNewest);
  const demos = (runs ?? [])
    .filter((m) => m.source === "simulator" && m.kind === "demo")
    .sort(byNewest);

  return (
    <>
      <h2>&gt; HARDWARE RUNS</h2>
      <p>
        Result cards and dashboard screenshots captured while jobs ran on a real IBM quantum
        computer. These are saved images: this app never contacts IBM.
      </p>

      {runs === null && <div className="note">Loading saved runs…</div>}

      {runs !== null && hardware.length === 0 && (
        <div className="note">
          No hardware runs saved yet. Run notebooks/03_real_hardware.ipynb, then commit
          docs/hardware_runs/.
        </div>
      )}

      {hardware.map((m) => (
        <div key={m.image} style={{ marginBottom: "1.4rem" }}>
          <div className="card">
            <h4>{m.kind === "dashboard" ? "DASHBOARD SCREENSHOT" : "RUN CARD"}</h4>
            <p className="small">
              backend {m.backend ?? "?"} | job {m.job_id ?? "?"} | {m.timestamp ?? ""}
            </p>
            <p>{m.caption ?? ""}</p>
          </div>
          <img className="run-image" src={m.image} alt={m.caption ?? "Hardware run"} />
        </div>
      ))}

      {demos.map((m) => (
        <div key={m.image} style={{ marginTop: "1.8rem" }}>
          <h3>&gt; SIMULATOR EXAMPLE — NOT IBM HARDWARE</h3>
          <div className="card card-demo">
            <h4>SIMULATED EXAMPLE</h4>
            <p className="small">
              source {m.backend ?? "?"} | job {m.job_id ?? "none"} | {m.timestamp ?? ""}
            </p>
            <p>{m.caption ?? ""}</p>
          </div>
          <img className="run-image" src={m.image} alt={m.caption ?? "Simulator example"} />
          <p className="caption">
            Generated by the local simulator. It is not a result from IBM hardware.
          </p>
        </div>
      ))}
    </>
  );
}
