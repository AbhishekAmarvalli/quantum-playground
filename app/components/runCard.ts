import { type Circuit, type Counts, sortedCounts } from "@/lib/quantum";

const GREEN = "#00ff41";
const DIM = "#00b32d";
const LIGHT = "#9dffb5";
const MONO = '600 13px ui-monospace, "JetBrains Mono", monospace';

/** Draw the downloadable run card (replaces qplay.render_snapshot). */
export function runCardDataUrl(
  circuit: Circuit,
  counts: Counts,
  shots: number,
  source = "simulator",
): string {
  const W = 800;
  const H = 600;
  const canvas = document.createElement("canvas");
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext("2d");
  if (!ctx) return "";

  ctx.fillStyle = "#000000";
  ctx.fillRect(0, 0, W, H);

  // ---------- circuit ----------
  ctx.fillStyle = GREEN;
  ctx.font = '600 15px ui-monospace, "JetBrains Mono", monospace';
  ctx.fillText("CIRCUIT", 40, 38);

  const n = circuit.nQubits;
  const x0 = 78;
  const colW = 56;
  const wireH = 34;
  const top = 78;
  const maxCols = Math.max(1, Math.floor((W - x0 - 70) / colW));
  const visible = circuit.ops.slice(0, maxCols);

  ctx.strokeStyle = "rgba(0,255,65,0.55)";
  ctx.lineWidth = 1;
  for (let q = 0; q < n; q++) {
    const y = top + q * wireH;
    ctx.beginPath();
    ctx.moveTo(40, y);
    ctx.lineTo(W - 40, y);
    ctx.stroke();
    ctx.fillStyle = DIM;
    ctx.font = MONO;
    ctx.fillText(`q${q}`, 46, y + 4);
  }

  const yOf = (q: number) => top + q * wireH;
  visible.forEach((op, i) => {
    const cx = x0 + colW * i + colW / 2;
    const label = op.gate.toUpperCase();
    if (op.qubits.length === 1) {
      const y = yOf(op.qubits[0]);
      ctx.fillStyle = "#020a02";
      ctx.strokeStyle = GREEN;
      ctx.fillRect(cx - 17, y - 12, 34, 24);
      ctx.strokeRect(cx - 17, y - 12, 34, 24);
      ctx.fillStyle = GREEN;
      ctx.font = '600 11px ui-monospace, monospace';
      ctx.textAlign = "center";
      ctx.fillText(label, cx, y + 4);
      ctx.textAlign = "left";
      return;
    }
    const controls = op.qubits.slice(0, -1);
    const target = op.qubits[op.qubits.length - 1];
    const ys = op.qubits.map(yOf);
    ctx.strokeStyle = GREEN;
    ctx.beginPath();
    ctx.moveTo(cx, Math.min(...ys));
    ctx.lineTo(cx, Math.max(...ys));
    ctx.stroke();
    controls.forEach((q) => {
      ctx.fillStyle = GREEN;
      ctx.beginPath();
      ctx.arc(cx, yOf(q), 4, 0, Math.PI * 2);
      ctx.fill();
    });
    const ty = yOf(target);
    ctx.fillStyle = "#020a02";
    ctx.fillRect(cx - 17, ty - 12, 34, 24);
    ctx.strokeRect(cx - 17, ty - 12, 34, 24);
    ctx.fillStyle = GREEN;
    ctx.font = '600 11px ui-monospace, monospace';
    ctx.textAlign = "center";
    const short = label === "SWAP" ? "SW" : label === "MCX" || label === "CCX" ? "X" : label;
    ctx.fillText(short, cx, ty + 4);
    ctx.textAlign = "left";
  });

  if (circuit.ops.length > visible.length) {
    ctx.fillStyle = DIM;
    ctx.font = MONO;
    ctx.fillText(`+${circuit.ops.length - visible.length} more gates`, W - 150, top - 8);
  }

  // ---------- histogram ----------
  ctx.fillStyle = GREEN;
  ctx.font = '600 15px ui-monospace, "JetBrains Mono", monospace';
  ctx.fillText(`RESULTS (${shots} shots, ${source})`, 40, 300);

  const items = sortedCounts(counts);
  const total = items.reduce((a, b) => a + b.count, 0) || 1;
  const plotL = 80;
  const plotR = W - 50;
  const plotT = 330;
  const plotB = 520;
  const plotH = plotB - plotT;
  const slot = (plotR - plotL) / Math.max(1, items.length);
  const barW = Math.min(60, slot * 0.6);

  ctx.strokeStyle = "rgba(0,255,65,0.25)";
  for (let t = 0; t <= 4; t++) {
    const yy = plotB - (plotH * t) / 4;
    ctx.beginPath();
    ctx.moveTo(plotL, yy);
    ctx.lineTo(plotR, yy);
    ctx.stroke();
    ctx.fillStyle = DIM;
    ctx.font = '11px ui-monospace, monospace';
    ctx.textAlign = "right";
    ctx.fillText(`${t * 25}%`, plotL - 8, yy + 4);
    ctx.textAlign = "left";
  }

  items.forEach((it, i) => {
    const p = it.count / total;
    const bx = plotL + slot * i + (slot - barW) / 2;
    const bh = Math.max(1, plotH * p);
    ctx.fillStyle = GREEN;
    ctx.fillRect(bx, plotB - bh, barW, bh);
    ctx.strokeStyle = LIGHT;
    ctx.strokeRect(bx, plotB - bh, barW, bh);
    ctx.fillStyle = LIGHT;
    ctx.font = '11px ui-monospace, monospace';
    ctx.textAlign = "center";
    ctx.fillText(`${Math.round(p * 100)}%`, bx + barW / 2, plotB - bh - 6);
    ctx.fillStyle = "#b6ffc8";
    ctx.font = '12px ui-monospace, monospace';
    ctx.fillText(it.key, bx + barW / 2, plotB + 20);
    ctx.textAlign = "left";
  });

  ctx.fillStyle = DIM;
  ctx.font = '10px ui-monospace, monospace';
  ctx.fillText("Generated by the local simulator - not IBM hardware", 40, H - 24);

  return canvas.toDataURL("image/png");
}
